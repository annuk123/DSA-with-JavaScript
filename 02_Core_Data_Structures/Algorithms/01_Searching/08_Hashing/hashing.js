hashTable.insert(5, 'apple');
hashTable.insert(15, 'banana');
hashTable.insert(25, 'cherry');

console.log(hashTable.search(5)); // Output: 'apple'
hashTable.delete(5);
console.log(hashTable.search(5)); // Output: null

