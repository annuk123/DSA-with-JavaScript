// Hashing is a technique used to map data to a fixed-size array, known as a hash table, in order to efficiently store and retrieve data. It is commonly used in data structures and algorithms to speed up operations such as searching, insertion, and deletion.

// Hashing works by applying a hash function to the input data, which generates a unique hash code or hash value. This hash code is used as an index to store the data in the hash table. When retrieving the data, the hash function is applied again to generate the hash code, which is used to look up the data in the hash table.

// Hashing has several advantages, including:
// - Fast access to data: Hashing allows for constant-time access to data, making it efficient for storing and retrieving data.
// - Efficient searching: Hashing can be used to quickly search for data in a large dataset by mapping the data to a fixed-size array.
// - Collision resolution: Hashing provides techniques to handle collisions, where multiple data elements map to the same index in the hash table.

// There are different types of hash functions and collision resolution techniques that can be used in hashing. Some common hash functions include:
// - Division method: The hash code is generated by taking the remainder of the division of the input data by the size of the hash table.
// - Multiplication method: The hash code is generated by multiplying the input data by a constant factor and taking the fractional part of the result.
// - Folding method: The input data is divided into equal-sized parts, which are then added together to generate the hash code.

// Collision resolution techniques are used to handle cases where multiple data elements map to the same index in the hash table. Some common collision resolution techniques include:
// - Chaining: In chaining, each index in the hash table stores a linked list of data elements that map to the same index.
// - Open addressing: In open addressing, when a collision occurs, the algorithm searches for an empty slot in the hash table to store the data element.

//Example of hashing using the division method and chaining collision resolution technique:

class HashTable {
    constructor(size) {
        this.size = size;
        this.table = new Array(size).fill(null).map(() => []);
    }

    hash(key) {
        return key % this.size;
    }

    insert(key, value) {
        const index = this.hash(key);
        this.table[index].push({ key, value });
    }

    search(key) {
        const index = this.hash(key);
        for (const item of this.table[index]) {
            if (item.key === key) {
                return item.value;
            }
        }
        return null;
    }

    delete(key) {
        const index = this.hash(key);
        this.table[index] = this.table[index].filter(item => item.key !== key);
    }
}

